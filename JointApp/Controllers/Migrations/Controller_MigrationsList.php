    public function getNewView():void
    {
        parent::getNewView();

        $this->view->editFields['add_date']['curVal'] = date('Y-m-d H:i:s');
        $this->view->editFields['add_date']['readonly'] = true;
        $this->view->editFields['status']['curVal'] = 'new';
