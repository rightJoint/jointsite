namespace JointApp\Views\User;

use JointApp\Interfaces\LangWebViewInterface;
use JointApp\Views\SiteView;

class View_User_Validate extends SiteView
{
    protected string $logo = '/img/popimg/checkInNow.png';
    public string $shortcutIcon = '/img/popimg/checkInNow.png';

    public string $vldRes = 'undefined';

    public bool $robotNoIndex = true;

    public static function loadLangView(string $docRoot = __DIR__, string $viewLang = 'ru', $loads = []):LangWebViewInterface
    {
        $name = 'LangFiles_'.self::langNs($viewLang).'_Views_User_Validate';
        $loads[] = [$name => $docRoot.'/JointApp/LangFiles/Views/User/'.$name];

        return parent::loadLangView($docRoot, $viewLang, $loads);
    }

    public function addViewParams(callable $addViewParams)
    {
        parent::addViewParams($addViewParams); // TODO: Change the autogenerated stub
        $viewParams = new \stdClass();
        $viewParams->vldRes = $this->vldRes;
        $addViewParams($viewParams);
    }

    public static function createPageContent(\stdClass $langPageContent, \stdClass $viewParams): string
    {
        $return = $langPageContent->vldErr[$viewParams->vldRes];
        return $return;
    }


}