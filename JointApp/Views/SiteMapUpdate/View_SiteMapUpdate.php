<?php


namespace JointApp\Views\SiteMapUpdate;


use JointApp\Views\SiteView;
use JointApp\Views\Modules\ModuleSubMenu;
use JointApp\Interfaces\LangWebViewInterface;

class View_SiteMapUpdate extends SiteView
{
    public string $logo = '/img/popimg/sitemap.png';
    public string $shortcutIcon = '/img/popimg/sitemap.png';

    public $bindComponents = [];

    public string $moduleName = '';

    public static function loadLangView(string $docRoot = __DIR__, string $viewLang = 'ru', $loads = []): LangWebViewInterface
    {
        $name = 'LangFiles_'.self::langNs($viewLang).'_Views_SiteMapUpdate';
        $loads[] = [$name => $docRoot.'/JointApp/LangFiles/Views/SiteMapUpdate/'.$name];
        return parent::loadLangView($docRoot, $viewLang, $loads);
    }

    public function addViewParams($addViewParams)
    {
        parent::addViewParams($addViewParams);
        $addParams = new \stdClass();
        $addParams->bindComponents = $this->bindComponents;
        $addParams->moduleName = $this->moduleName;
        $addViewParams($addParams);
    }

    public static function addStyleLinks(callable $addStyleLinks): void
    {
        parent::addStyleLinks($addStyleLinks); // TODO: Change the autogenerated stub
        $addStyleLinks(['/css/modules/moduleMenu.css',]);
    }

    public static function createPageContent(\stdClass $langPageContent, \stdClass $viewParams): string
    {
        return ModuleSubMenu::bindModuleMenu($viewParams->bindComponents, $viewParams->userModules, $langPageContent->modulesMenu, $viewParams->moduleName).
            self::getLangMap(); // TODO: Change the autogenerated stub
    }

    public static function getLangMap():string
    {
        return '<div class="contentBlock-frame"><div class="contentBlock-center">'.
            '<div class="contentBlock-wrap">'.
            '<a href="/sitemap.xml" title="sitemap.xml">sitemap.xml</a>'.
            '</div></div></div>';
    }
}