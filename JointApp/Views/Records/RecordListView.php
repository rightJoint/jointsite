    }

    public static function ctrlLine($langFilterView, \stdClass $viewParams = null)
    {
        $return_ajax = '<div class="ctrl-line">'.
            '<div class="pagination">'.
            static::listPgView($langFilterView, $viewParams);

        $return_ajax.= '</div>'.
            '<div class="sort-block">'.
            '<span class="found_label">'.$langFilterView->list_table['list_by'].': </span>'.
            '<select name="onPage">';
        foreach ($viewParams->onPage_list as $onPage){
            $return_ajax.= '<option value="'.$onPage.'"';
            if($onPage == $viewParams->onPage){
                $return_ajax.= ' selected';
            }
            $return_ajax.= '>'.$onPage.'</option>';
        }


        $sortOrder_asc = 'selected';
        $sortOrder_desc = null;
        $count_of = 0;
        $sortFields_options = null;
        foreach ($viewParams->searchFields as $fieldName=>$fieldData){
            if($fieldData['format'] != 'hidden'){
                $count_of++;
                if($count_of == 1){
                    if(isset($fieldData['sortOrder']) and $fieldData['sortOrder'] == 'DESC'){
                        $sortOrder_desc = 'selected';
                        $sortOrder_asc = null;
                    }
                }

                if(isset($viewParams->fieldAliases[$fieldName])){
                    $option_text = $viewParams->fieldAliases[$fieldName];
                }else{
                    $option_text = $fieldName;
                }

                $sortFields_options.='<option value="'.$fieldName.'">'.$option_text.'</option>';


            }
        }
        $return_ajax.= '</select>'.
            '<span class="sortField">'.$langFilterView->list_table['sort'].': </span>'.
            '<select name="sortField">'.$sortFields_options.'</select>'.
            '<select name="sortOrder"><option value="ASC" '.$sortOrder_asc.'>ASC</option><option value="DESC" '.$sortOrder_desc.'>DESC</option></select>'.
            '</div>'.
            '<div class="new-block">';
        if($viewParams->hasAccessCreate){
            $return_ajax.='<a href="'.$viewParams->langSl.$viewParams->process_url.'/newview'.
                $viewParams->newBtn_qry.'" class="newRecLink">'.$langFilterView->list_table['new'].'</a>';
        }

        $return_ajax.='</div>'.
            '</div>';
        return $return_ajax;
    }

    public static function listViewTable($langFilterView, \stdClass $viewParams = null)
    {
        $return_text = null;

        if($viewParams->listRecords){
            $return_text .= '<table>'.
                '<tr class="fCaption">';
            foreach ($viewParams->listFields as $fieldName => $fieldInfo){

                $return_text.= '<td';
                if(isset($fieldInfo['format']) and ( $fieldInfo['format']== 'hidden')){
                    $return_text.= ' style="display:none;"';
                }
                $return_text.='>';
                if ($fieldName == 'btnEdit'){
                    $return_text.= $langFilterView->list_table['cell_edit'];
                }elseif ($fieldName == 'btnDelete'){
                    $return_text.= $langFilterView->list_table['cell_del'];
                }elseif ($fieldName == 'btnDetail'){
                    $return_text.= $langFilterView->list_table['cell_view'];
                }elseif(isset($viewParams->fieldAliases[$fieldName])){
                    $return_text.= $viewParams->fieldAliases[$fieldName];
                }else{
                    $return_text.= $fieldName;
                }
                $return_text.= '</td>';
            }
            $return_text.= '</tr>';

            foreach($viewParams->listRecords as $row_num => $row){
                $return_text.= '<tr>';
                foreach ($viewParams->listFields as $fieldName => $fieldInfo){
                    $name_print = null;
                    if(isset($fieldInfo['useName'])){
                        $name_print = ' name="'.$row[$fieldInfo['useName']].'" ';
                    }

                    $return_text.= '<td';
                    if(isset($fieldInfo['format']) and ($fieldInfo["format"] == 'hidden')){
                        $return_text.= ' style="display:none;"';
                    }
                    $return_text.= '>';

                    if ($fieldInfo['format'] == 'file'){

                        if($row[$fieldName]){
                            if($fieldInfo['file_options']['file_type'] == 'img'){
                                $imgLink = null;
                                if($fieldInfo['file_options']['load_dir']){

                                    if(isset($fieldInfo['replaces'])){
                                        $imgLink = $fieldInfo['file_options']['load_dir'];
                                        if($fieldInfo['replaces']){
                                            foreach ($fieldInfo['replaces'] as $replace){
                                                $imgLink = str_replace($replace, $row[$replace], $imgLink);
                                            }
                                        }
                                    }else{
                                        $imgLink = $fieldInfo['file_options']['load_dir'].'/'.$row[$fieldName];
                                    }
                                }

                                if($imgLink){
                                    $return_text.='<img class="cell-img" src="'.$imgLink.'">';
                                }else{
                                    $return_text.= 'file:'.$fieldInfo['file_options']['file_type'].':'.$fieldInfo['file_options']['load_dir'].'='.
                                        $row[$fieldName];
                                }
                            }else{
                                $return_text.= 'file:'.$fieldInfo['file_options']['file_type'].':'.$fieldInfo['file_options']['load_dir'].'='.
                                    $row[$fieldName];
                            }
                        }
                    }elseif($fieldInfo['format'] == 'link'){
                        if(in_array($fieldName, array('btnDetail', 'btnEdit', 'btnDelete'))){
                            $urlLink = null;
                            if($fieldInfo['replaces']){
                                $urlLink = $fieldInfo['url'];
                                foreach ($fieldInfo['replaces'] as $replace){
                                    $repl_pos = strpos($urlLink, $replace);
                                    $urlLink_1 = substr($urlLink, 0, $repl_pos+strlen($replace)+1);
                                    $urlLink_2 = substr($urlLink, $repl_pos+strlen($replace)+1, strlen($urlLink));
                                    $urlLink_3 = str_replace($replace, $row[$replace], $urlLink_2);
                                    $urlLink = $urlLink_1.$urlLink_3;
                                }
                            }
                            //$urlLink .="&".$this->slave_req;
                            if ($fieldName == 'btnDetail'){
                                $return_text.= '<a href="'.$viewParams->langSl.$viewParams->process_url.'/detailview?'.
                                    $urlLink.'" class="list-btn">'.
                                    '<img src="/img/popimg/eye-icon.png"></a>';
                            }elseif ($fieldName == 'btnEdit'){
                                if(!isset($row['btnEdit']) or $row['btnEdit']!='disabled'){
                                    $return_text.= '<a href="'.$viewParams->langSl.$viewParams->process_url.'/editview?'.
                                        $urlLink.'" class="list-btn">'.
                                        '<img src="/img/popimg/edit-icon.png"></a>';
                                }
                            }elseif ($fieldName == 'btnDelete'){
                                if(!isset($row['btnDelete']) or $row['btnDelete']!='disabled'){
                                    $return_text.= '<a href="'.$viewParams->langSl.$viewParams->process_url.'/deleteview?'.
                                        $urlLink.'" class="list-btn">'.
                                        '<img src="/img/popimg/drop-icon.png"></a>';
                                }
                            }
                        }else{
                            $urlLink = null;
                            if($fieldInfo['replaces']){
                                $urlLink = $fieldInfo['url'];
                                foreach ($fieldInfo['replaces'] as $replace){
                                    $repl_pos = strpos($urlLink, $replace);
                                    $urlLink_1 = substr($urlLink, 0, $repl_pos+strlen($replace)+1);
                                    $urlLink_2 = substr($urlLink, $repl_pos+strlen($replace)+1, strlen($urlLink));
                                    $urlLink_3 = str_replace($replace, $row[$replace], $urlLink_2);
                                    $urlLink = $urlLink_1.$urlLink_3;
                                }
                            }
                            $return_text.= "<a href='".$viewParams->langSl.$urlLink."' title='edit'>".$row[$fieldName]."</a>";
                        }
                    }elseif($fieldInfo['format'] == 'ref'){
                        $urlLink = null;
                        if($fieldInfo['replaces']){
                            $urlLink = $fieldInfo['url'];
                            foreach ($fieldInfo['replaces'] as $replace){
                                $urlLink = str_replace($replace, $row[$replace], $urlLink);
                            }
                        }
                        $return_text.= '<a href="'.$viewParams->langSl.$viewParams->process_url.'/'.$urlLink.'" title="edit">'.$row[$fieldName].'</a>';

                    }elseif (($fieldInfo['format'] == 'varchar') or ($fieldInfo['format'] =='text')){
                        if(isset($fieldInfo['max_length']) and isset($row[$fieldName]) and  $fieldInfo['max_length'] < strlen($row[$fieldName]) ){
                            $return_text.= mb_substr($row[$fieldName], 0, $fieldInfo["max_length"]).' ...';
                        }else {
                            $return_text.=  $row[$fieldName];
                        }
                    }elseif (($fieldInfo['format'] == 'int') or ($fieldInfo['format'] =='float')
                        or ($fieldInfo['format'] =='datetime')or ($fieldInfo['format'] =='date')){
                        $return_text.=  $row[$fieldName];
                    }elseif (($fieldInfo['format'] == 'tinyint') or ($fieldInfo['format'] == 'checkbox')){
                        $return_text.= '<input type="checkbox" '.$name_print;
                        if($row[$fieldName]){
                            $return_text.= 'checked';
                        }
                        $return_text.='>';
                    }elseif ($fieldInfo['format'] == 'select'){
                        $return_text.= $fieldInfo['filling'][$row[$fieldName]];
                    }
                    else{
                        $custom_type = static::getCustomListType($fieldName, $row[$fieldName]);
                        if($custom_type != null){
                            $return_text.=$custom_type;
                        }else{
                            $return_text.= '<span>[format='.$fieldInfo['format'].']:</span>'.$row[$fieldName];
                        }
                    }
                    $return_text.= '</td>';
                }
                $return_text.= '</tr>';
            }
            $return_text.= '</table>';
        }
        return $return_text;
    }

