    private static function filterView(\stdClass $langFilterView, \stdClass $viewParams = null)
    {
        $return_text = '<div class="contentBlock-frame"><div class="contentBlock-center">'.
            '<div class="contentBlock-wrap">'.
            '<div class="search_frame">'.
            '<form class="filterForm" method="post">';
        if(isset($viewParams->searchFields)){
            if(count($viewParams->searchFields)){
                foreach ($viewParams->searchFields as $fieldName=>$fieldData){
                    if(isset($fieldData['search']) and $fieldData['search'] == true){
                        if(isset($viewParams->fieldAliases[$fieldName])){
                            $name_input = $viewParams->fieldAliases[$fieldName];
                        }else{
                            $name_input = $fieldName;
                        }

                        $htmlInput = self::getInputType($fieldName, $fieldData, $name_input);
                        $return_text.=$htmlInput->getHtml();
                    }
                }
            }
        }


        $return_text.= '<div class="apply-line">';
        $return_text.= '<input type="button" class="applyFilterForm" '.
            'value="'.$langFilterView->list_table['btn_clear'].'" '.
            'onclick="clearSearchInputs()">'.
            '<input type="button" class="applyFilterForm" '.
            'value="'.$langFilterView->list_table['btn_apply'].'" '.
            'onclick="applyFilterForm()">'.
            '</div>'.
            '<input type="hidden" name="applyFilterRec" value="1">'.
            '</form>'.
            '</div>'.
            '</div>'.
            '</div>'.
            '</div>';

        return $return_text;
    }

    public static function listView($langFilterView, \stdClass $viewParams = null):string
    {
        $return = '<div class="contentBlock-frame"><div class="contentBlock-center">'.
            '<div class="contentBlock-wrap">'.
            '<div class="list_frame" id="'.$viewParams->list_frame_id.'">';
        if($viewParams->h2){
            $return.= '<h2>'.$viewParams->h2.'</h2>';
        }
        $return.= static::ctrlLine($langFilterView, $viewParams).
            '<div class="list_table">'.
            static::listViewTable($langFilterView, $viewParams).
            '</div>'.
            static::scriptListViewCrtlPannel($viewParams->list_frame_id, $viewParams->process_url, $viewParams->slave_req).
            self::scriptSortBlock($viewParams->list_frame_id).
            '</div>'.
            '</div>'.
            '</div>'.
            '</div>';

        return $return;
    }

    private static function scriptSortBlock(string $list_frame_id = ''):string
    {
        return '<script>$("#'.$list_frame_id.'").recordsSortBlock();</script>';
    }

    public static function scriptListViewCrtlPannel(string $list_frame_id = '', string $process_url = '', string $slave_req = '')
    {
        return '<script>$("#'.$list_frame_id.'").recordsPgBlock("'.$process_url.'", "'.$slave_req.'");</script>';
    }

