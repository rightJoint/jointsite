<?php


namespace JointApp\Views\Modules;


use JointApp\Views\Records\RecordDetailView;

class ModuleDetailView extends RecordDetailView
{
    public $bindComponents = [];
    public string $moduleName = '';

    public bool $robotNoIndex = true;

    public function addViewParams($addViewParams)
    {
        parent::addViewParams($addViewParams);
        $addParams = new \stdClass();
        $addParams->bindComponents = $this->bindComponents;
        $addParams->moduleName = $this->moduleName;
        $addViewParams($addParams);
    }

    public static function addStyleLinks(callable $addStyleLinks): void
    {
        parent::addStyleLinks($addStyleLinks); // TODO: Change the autogenerated stub
        $addStyleLinks(['/css/modules/moduleMenu.css',]);
    }

    public static function createPageContent(\stdClass $langPageContent, \stdClass $viewParams): string
    {
        return ModuleSubMenu::bindModuleMenu($viewParams->bindComponents, $viewParams->userModules, $langPageContent->modulesMenu, $viewParams->moduleName).
            parent::createPageContent($langPageContent, $viewParams); // TODO: Change the autogenerated stub
    }
}