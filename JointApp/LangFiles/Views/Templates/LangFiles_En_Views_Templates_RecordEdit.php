<?php
class LangFiles_En_Views_Templates_RecordEdit extends LangFiles_En_Views_SiteView
{
    public static function getLangPageContent(): stdClass
    {
        $lang = parent::getLangPageContent(); // TODO: Change the autogenerated stub

        $editView = new stdClass();
        $editView->submitUpdate = 'Update';
        $editView->submitNew = 'Create';
        $editView->submitDel = 'Delete';

        $lang->editView = $editView;
        return $lang;
    }

    public static function getLangHeader(): stdClass
    {
        $langHeader = parent::getLangHeader();

        $langHeader->updateFromArray = function ($array = []) use (&$langHeader){
            if($array['type'] == 'edit'){
                $langHeader->h1 = 'Edit record in table '.$array['tableName'];
            }elseif ($array['type'] == 'new'){
                $langHeader->h1 = 'Create record in table '.$array['tableName'];
            }elseif ($array['type'] == 'delete'){
                $langHeader->h1 = 'Delete record from table '.$array['tableName'];
            }
        };
        return $langHeader;
    }
}
