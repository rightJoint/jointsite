<?php


namespace Src\Views\Blog\IT;


use Src\Views\Blog\View_Blog_Art;

class View_Blog_IT_TestTaskAlvasar extends View_Blog_Art
{

    public string $fio = 'Шишкова Ирина Валентиновна';
    public string $birthday = '1964-05-13';

    public static function addStyleLinks(callable $addStyleLinks): void
    {
        parent::addStyleLinks($addStyleLinks); // TODO: Change the autogenerated stub
        $addStyleLinks([
            '/css/blog/alvasar.css',
        ]);
    }

    public function addViewParams(callable $addViewParams)
    {
        parent::addViewParams($addViewParams); // TODO: Change the autogenerated stub
        $addParams = new \stdClass();
        $addParams->fio = $this->fio;
        $addParams->birthday = $this->birthday;
        $addViewParams($addParams);
    }

    public static function addScriptLinks(callable $addScriptLinks): void
    {
        parent::addScriptLinks($addScriptLinks); // TODO: Change the autogenerated stub
        $addScriptLinks([
            '/js/blog/testTasksAjax.js',
        ]);
    }

    public static function printArtContent(\stdClass $langArtContent, \stdClass $viewParams, string $langLw): string
    {
        return self::alvasarTask().
            self::alvasarTest($viewParams->birthday, $viewParams->fio).
            self::alvasarCode().
            self::alvasarConclusion();;
    }

    public static function alvasarTask():string
    {
        return '<section>'.
            '<h3>Постановка задачи</h3>'.
            '<p>Пользователь вводит свои ФИО и дату рождения, на выходе получает код судьбы. '.
            'Методика расчета кода дана в описании задачи <a href="/downloads/Тестовое задание Альвасар.docx">Тестовое задание Альвасар.docx</a>'.
            '</p>'.
            '</section>';
    }

    public static function alvasarTest(string $birthday, string $fio):string
    {
        $return = '<section>'.
            '<h3>Тест</h3>'.
            '<p>Введите ваши Фамилию, Имя, отчество, дату рождения и нажмите "получить код!":</p>'.
            '<div class="alvasar-test">'.
            '<form>'.
            '<div class="alvasar-input-line">'.
            '<label for="fio">ФИО</label>'.
            '<input type="text" id="fio" name="fio" placeholder="Ваше Фамилия Имя Отчество" value="'.$fio.'">'.
            '<p><small>Допускаются только русские буквы.</small></p>'.
            '</div>'.
            '<div class="alvasar-input-line">'.
            '<label for="birthday">Д.р.</label>'.
            '<input type="date" id="birthday" name="birthday" value="'.$birthday.'">'.
            '</div>';

        $birthday_date = new \DateTime($birthday);
        $birthday_trim = date_format($birthday_date, 'd.m.Y');
        $birthday_trim = str_replace('.', '', $birthday_trim);

        $alvasarCode = @AlvasarCode::calcCode($birthday_trim, $fio);

        $return.= '<div>'.
            '<input type="button" onclick="calcAlvasarCode()" value="Получить код!">'.
            '</div>'.
            '<div class="alvasar-code-result">'.
            '<span class="code-label">ИТОГОВЫЙ  ЦИФРОВОЙ КОД</span>'.
            '<span class="code-value">'.$alvasarCode.'</span>'.
            '</div>'.
            '</form>'.
            '</div>'.
            '</section>';
        return $return;
    }

    public static function alvasarCode():string
    {
        $return = '<section>'.
            '<h3>php-код</h3>'.
            '<p>В коде использовалось много рекурсий, все методы реализованы в одном классе, '.
            '<a href="/downloads/AlvasarCode.php.txt">скачать AlvasarCode.php.txt</a></p>'.
            '</section>';
        return $return;
    }

    public static function alvasarConclusion():string
    {
        $return = '<section>'.
            '<h3>Выводы</h3>'.
            '<p>'.
            'Хотя реальных причин срыва контракта мне не назвали, '.
            'я считаю что получил бонус в виде кармы) Не связываться с магами, гадалками, '.
            'менталистами, колдунами, цыганями - походу это не про меня.</p>'.
            '</section>';
        return $return;
    }
}