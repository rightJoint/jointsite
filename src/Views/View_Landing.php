    public static function printBlogCards(\stdClass $artLang, array $artList, array $artTags, string $langSl):string
    {
        $return = '';
        $return.= '<div class="contentBlock-frame dark"><div class="contentBlock-center">'.
            '<div class="contentBlock-wrap">'.
            '<div class="landing-blog">'.'<section class="dark">'.
            '<h2 style="color: silver; margin-top: 1em">'.$artLang->h2.'</h2>'.
            '</section>';

        $blog_arts = null;
        $artsDev_cnt = 0;
        $artsPc_cnt = 0;

        $groupTags = [];

        foreach($artList as $num => $slArt_row){

            $printTags = '';
            foreach ($artTags[$slArt_row['art_id']] as $num=>$tag_info){
                if(isset($groupTags[$tag_info['tagName']])){
                    $groupTags[$tag_info['tagName']]++;
                }else{
                    $groupTags[$tag_info['tagName']]=1;
                }
                $printTags .='<span class="bPc">'.$tag_info['tagName'].'</span>';
            }

            $blog_arts.="<article class='mini-card module module-article article'>".
                "<div class='pubDate'>".
                $artLang->article;
            if($slArt_row['pubDate']){
                $blog_arts.=' '.$artLang->from.' <b>'.$slArt_row['pubDate'].'</b>';
            }

            $blog_arts.="</div><h4 class='mini-card-title'>".
                "<a href='".$langSl."/blog/article/".$slArt_row['artRef']."'>".$slArt_row['artName']."</a>".
                "</h4>".
                "<div class='tags'>".$slArt_row['artMeta']."</div>".
                "<div class='art_bottom'>";

            if($slArt_row['artImg']){
                $blog_arts.=
                    '<img alt="art-img" src="'.self::ART_COVERS.'/'.$slArt_row['artImg'].'">';
            }else{
                $blog_arts.= "<img src='/img/popimg/default-img.png'>";
            }

            $blog_arts.= $printTags;
            $blog_arts.="</div>".
                "</article>";
            $artsPc_cnt++;

        }
        $return.= '<div class="popular-articles">'.
            '<div class="popular-header">'.
            '<h3 class="header-card-title">'.$artLang->h2.'</h3>'.
            '<div class="header-card-info">'.
            '<span>'.$artLang->written.' '.($artsDev_cnt+$artsPc_cnt).' '.$artLang->arts.'</span>'.
        '<span class="tg-label">'.$artLang->tags.'</span>';

        foreach ($groupTags as $tagName=>$tagCount){
            $return.= '<span class="tg-item">'.$tagName.' ('.$tagCount.')</span>';
        }
        $return.='</div>'.
            '</div>'.
            '<div class="mini-card-grid">'.$blog_arts.'</div></div>';

        $return.= '</div>'.
            '</div>'.
            '</div>'.
            '</div>';

        return $return;
    }
