<?php


namespace Src\Views\Handbook;


use JointApp\Views\SiteView;
use JointApp\Interfaces\LangWebViewInterface;

class View_Handbook_Main extends SiteView
{
    public int $envCount = 0;
    public int $hvCount = 0;
    public int $processCount = 0;
    public int $servicesCount = 0;

    public function addViewParams($addViewParams)
    {
        parent::addViewParams($addViewParams);
        $addParams = new \stdClass();
        $addParams->envCount = $this->envCount;
        $addParams->hvCount = $this->hvCount;
        $addParams->processCount = $this->processCount;
        $addParams->servicesCount = $this->servicesCount;
        $addViewParams($addParams);
    }

    public static function loadLangView(string $docRoot = __DIR__, string $viewLang = 'ru', $loads = []): LangWebViewInterface
    {
        $name = 'LangFiles_'.self::langNs($viewLang).'_Views_Handbook_Main';
        $loads[] = [$name => $docRoot.'/LangFiles/Views/Handbook/'.$name];
        return parent::loadLangView($docRoot, $viewLang, $loads);
    }

    public static function addStyleLinks(callable $addStyleLinks): void
    {
        parent::addStyleLinks($addStyleLinks); // TODO: Change the autogenerated stub

        /*
        $addStyleLinks([
            '/css/cv/cv-header.css',
            '/css/cv/cv-menu.css',
        ]);
        */
    }

    public static function createPageContent(\stdClass $langPageContent, \stdClass $viewParams):string
    {

        //echo '<pre>';
        //print_r($viewParams);
        //exit;

        return self::hbEnvironment($viewParams->envCount).
            self::hbHardware($viewParams->hvCount).
            self::hbProcess($viewParams->processCount).
            self::hbServices($viewParams->servicesCount);

        /*
            '<div class="contentBlock-frame"><div class="contentBlock-center">'.
