            self::cvHeader($langPageContent->cvHeader).
            self::cvMenu($langPageContent->cvMenu, $viewParams->langSl, $viewParams->routes_ns).
            static::cvContent($langPageContent->cvContent).
            '</div>'.
            '</div>'.
            '</div>';
        */
    }

    public static function hbEnvironment(int $envCount):string
    {
        return
            '<div class="hb-menu-block">'.
            '<div class="hb-menu-block-img">'.
            '<img src="/img/handbook/env.png">'.
            '</div>'.
            'hbEnvironment = '.$envCount.
            '</div>';
    }

    public static function hbHardware(int $hvCount):string
    {
        return
            '<div class="hb-menu-block">'.
