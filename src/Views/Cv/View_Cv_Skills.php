<?php

namespace Src\Views\Cv;



use JointApp\Interfaces\LangWebViewInterface;
use Src\Views\Blog\IT\SkillsTableTrait;

class View_Cv_Skills extends View_Cv_Main
{

    use SkillsTableTrait;

    public static function loadLangView(string $docRoot = __DIR__, string $viewLang = 'ru', $loads = []): LangWebViewInterface
    {
        $name = 'LangFiles_'.self::langNs($viewLang).'_Views_Cv_Skills';
        $loads[] = [$name => $docRoot.'/LangFiles/Views/Cv/'.$name];
        return parent::loadLangView($docRoot, $viewLang, $loads);
    }

    public static function addStyleLinks(callable $addStyleLinks): void
    {
        parent::addStyleLinks($addStyleLinks); // TODO: Change the autogenerated stub
        $addStyleLinks([
            '/css/cv/skills-table.css',
            '/css/cv/cv-skills.css',
        ]);
    }

    public static function cvContent():string
    {
        return self::cvSillsTable();
    }

    public static function cvSillsTable():string
    {
        return '<section class="cv-skills">'.
            '<h3>Профессиональные навыки</h3>'.
            '<div class="cv-skills-tb1">'.
            '<p>'.
            'Заказчику часто требуется чтоб сотрудник умел работать сразу с несколькими '.
            'инструментами/технологиями. Но сейчас стек настолько широк что на получение глубокого '.
            'практического опыта потребуются десятилетия. '.
            'Я составил примерную шкалу для оценки своих навыков.</p>'.
            '</div>'.
            self::skillsLegendTable().
            '<div class="cv-skills-tb2">'.
            '<p>Список наиболее востребованных навыков, '.
            'которые часто запрашиваются в описании к вакансиям и свой опыт по ним я '.
            'описал в таблице.</p>'.
            '</div>'.
            '<div class="t-wrap">'.
            self::skillsTable().
            '</div>'.
            '</section>';
    }
}